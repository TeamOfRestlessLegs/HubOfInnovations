package pl.hackathon.hubofinnovations.innovations.adapter.out.persistence;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;
import pl.hackathon.hubofinnovations.innovations.domain.model.Category;
import pl.hackathon.hubofinnovations.innovations.domain.model.Innovation;
import pl.hackathon.hubofinnovations.innovations.domain.model.InnovationFile;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@DataJpaTest
@Import({InnovationRepositoryAdapter.class, CategoryRepositoryAdapter.class})
class InnovationRepositoryAdapterTest {

    @Autowired
    private InnovationRepositoryAdapter innovationRepositoryAdapter;

    @Autowired
    private CategoryRepositoryAdapter categoryRepositoryAdapter;

    @Test
    void shouldSaveAndRetrieveInnovationWithFiles() {
        // given - prepare a category and save it
        Category category = new Category("edukacja", "Edukacja", "http://test.pl");
        categoryRepositoryAdapter.save(category);

        // create a new innovation with a file
        InnovationFile file = new InnovationFile(null, "materialy", "test.pdf", "url", null, "/storage/test.pdf", 1024L, true, 5);
        Innovation innovation = new Innovation(
                "edukacja/aplikacja-szkolna", category, "aplikacja-szkolna", "Aplikacja",
                "Krótki opis", "Markdown", "http://source.pl", null, null,
                OffsetDateTime.now(), "hash", List.of(file)
        );

        // when - save using the adapter
        Innovation saved = innovationRepositoryAdapter.save(innovation);
        Optional<Innovation> retrieved = innovationRepositoryAdapter.findById("edukacja/aplikacja-szkolna");

        // then
        assertTrue(retrieved.isPresent());
        assertEquals("Aplikacja", retrieved.get().title());
        assertEquals("edukacja", retrieved.get().category().slug());
        assertEquals(1, retrieved.get().files().size());
        assertEquals("test.pdf", retrieved.get().files().get(0).fileName());
        assertNotNull(retrieved.get().files().get(0).id()); // File ID should be generated by the database
    }
}